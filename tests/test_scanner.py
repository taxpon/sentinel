def record(
    identifier: str,
    *,
    package: str,
    ecosystem: str = audit.PYPI,
    events: Sequence[Mapping[str, str]] = ({"introduced": "0"}, {"fixed": "9.9.9"}),
    aliases: Sequence[str] = (),
    summary: str = "A vulnerability",
    severity: str | None = "HIGH",
    withdrawn: str | None = None,
    references: Sequence[str] = (),
) -> dict[str, Any]:
    """One `GET /v1/vulns/{id}` body, shaped like the ones `api.osv.dev` actually returns."""
    body: dict[str, Any] = {
        "id": identifier,
        "summary": summary,
        "aliases": list(aliases),
        "affected": [
            {
                "package": {"name": package, "ecosystem": ecosystem},
                "ranges": [{"type": "ECOSYSTEM", "events": list(events)}],
            }
        ],
        "references": [{"type": "WEB", "url": url} for url in references],
    }
    if severity is not None:
        body["database_specific"] = {"severity": severity}
    if withdrawn is not None:
        body["withdrawn"] = withdrawn
    return body


