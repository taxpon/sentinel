"""Tests for the scheduled vulnerability sweep.

The sweep is judged on what it *does not* file, so most of this file is about rejection: an
advisory already filed, one a maintainer closed, one whose fix is a lock refresh, one with no fix
at all. The findings that do get through are asserted on the captured `POST /repos/…/issues` body
rather than on a return value, because the issue is the artefact — its class label picks the
playbook and its body is the whole of what a Devin session is told
(`.claude/rules/testing.md`, "assert the captured request").

OSV and GitHub are `respx` fakes over the real clients. The OSV fake answers `querybatch` from the
request it was sent, so a test that adds a package to the tree gets a truthful answer for it and
one that does not is not silently handed advisories for packages the scanner never asked about.

The manifests are cut down from `taxpon/superset` at the state
`docs/remediation-candidates.md` triaged: the paramiko pin and its two documented blockers, the
deck.gl family reaching `image-size` transitively, and the entries T50 examined and rejected.
"""

