def test_the_same_advisory_published_twice_is_one_advisory() -> None:
    installed = {(audit.PYPI, "paramiko"): "3.5.1"}
    pysec = record(
        PARAMIKO_PYSEC,
        package="paramiko",
        aliases=[PARAMIKO_CVE, PARAMIKO_GHSA],
        severity=None,
        events=({"introduced": "0"}, {"fixed": "5.0.0"}),
    )

    merged = audit._merge(
        audit.parse_advisory(entry, installed) for entry in (PARAMIKO_RECORD, pysec)
    )

    assert len(merged) == 1
    assert merged[0].id == PARAMIKO_GHSA
    assert merged[0].severity == "LOW", (
        "the record that stated a severity wins over the one that did not"
    )
    # The GHSA record has no `fixed` event; the PYSEC one does, and the fix is the better evidence.
    assert merged[0].affected[(audit.PYPI, "paramiko")] == ("5.0.0", "4.0.0")


