def finding(
    *,
    name: str = "paramiko",
    ecosystem: str = audit.PYPI,
    version: str = "3.5.1",
    constraint: str | None = None,
    fixed: str | None = "5.0.0",
    last_affected: str | None = None,
    identifier: str = "GHSA-example",
    aliases: Sequence[str] = (),
    severity: str = "HIGH",
    withdrawn: bool = False,
    manifest: bool = True,
) -> audit.Finding:
    line = audit.SourceLine("requirements/base.txt", 1, f"{name}=={version}") if manifest else None
    dependency = audit.Dependency(
        ecosystem=ecosystem,
        name=name,
        version=version,
        pinned_at=line,
        declared_at=audit.SourceLine("pyproject.toml", 9, f'"{name}{constraint}"')
        if constraint
        else None,
        constraint=constraint,
    )
    advisory = audit.Advisory(
        id=identifier,
        identifiers=frozenset({identifier, *aliases}),
        summary="A vulnerability",
        severity=severity,
        withdrawn=withdrawn,
        references=(),
        affected={(ecosystem, name): (fixed, last_affected)},
    )
    return audit.Finding(dependency, advisory, fixed, last_affected)


def reasons(decided: audit.Triage) -> dict[str, audit.Rejected]:
    return {entry.finding.advisory.id: entry.reason for entry in decided.skipped}


@pytest.mark.parametrize(
    ("case", "expected"),
    [
        # The declared range already permits the fix: nothing in the manifest changes.
        (
            {
                "name": "flask",
                "version": "2.3.3",
                "constraint": ">=2.2.5, <4.0.0",
                "fixed": "3.1.3",
            },
            audit.Rejected.LOCK_REFRESH,
        ),
        # The declared range refuses it: the cap has to be renegotiated.
        (
            {
                "name": "paramiko",
                "version": "3.5.1",
                "constraint": ">=3.4.0, <4.0",
                "fixed": "5.0.0",
            },
            None,
        ),
        (
            {
                "name": "cryptography",
                "version": "49.0.0",
                "constraint": ">=49.0.0, <50.0.0",
                "fixed": "50.0.0",
            },
            None,
        ),
        # Nothing declares it, and the fix stays inside the major.
        ({"name": "js-yaml", "version": "4.3.0", "fixed": "4.3.1"}, audit.Rejected.LOCK_REFRESH),
        # Nothing declares it, and the fix crosses the major.
        ({"name": "image-size", "version": "0.7.5", "fixed": "1.2.1"}, None),
        # Below 1.0 the minor is the boundary.
        (
            {"name": "python-multipart", "version": "0.0.29", "fixed": "0.0.30"},
            audit.Rejected.LOCK_REFRESH,
        ),
        ({"name": "python-multipart", "version": "0.0.29", "fixed": "0.1.0"}, None),
        # An unreadable range falls through to the boundary rather than being read as permission.
        (
            {
                "name": "xlsx",
                "version": "0.20.3",
                "constraint": "https://cdn.example/x.tgz",
                "fixed": "0.20.4",
            },
            audit.Rejected.LOCK_REFRESH,
        ),
        # Only a last-affected bound: the fix is above it, so the boundary is read from that.
        (
            {"name": "paramiko", "version": "3.5.1", "fixed": None, "last_affected": "4.0.0"},
            None,
        ),
        (
            {"name": "mcp", "version": "1.24.0", "fixed": None, "last_affected": "1.27.2"},
            audit.Rejected.LOCK_REFRESH,
        ),
    ],
)
def test_only_a_fix_that_forces_a_decision_is_filed(
    case: dict[str, Any], expected: audit.Rejected | None
) -> None:
    decided = audit.triage([finding(**case)], already_filed=frozenset())

    if expected is None:
        assert [candidate.finding.dependency.name for candidate in decided.file] == [case["name"]]
        assert decided.skipped == ()
    else:
        assert decided.file == ()
        assert [entry.reason for entry in decided.skipped] == [expected]


