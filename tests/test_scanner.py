async def test_every_rejection_is_reported_with_its_reason(
    scanner_settings: Settings, github_api: FakeAPI, osv_api: FakeAPI, capture: Any
) -> None:
    logs = capture()

    await run_sweep(scanner_settings, github_api, osv_api, records=ALL_RECORDS)

