def test_the_issue_body_carries_everything_a_remediation_needs() -> None:
    candidate = audit.Candidate(
        audit.Finding(
            audit.Dependency(
                ecosystem=audit.PYPI,
                name="paramiko",
                version="3.5.1",
                pinned_at=audit.SourceLine("requirements/base.txt", 283, "paramiko==3.5.1"),
                declared_at=audit.SourceLine(
                    "pyproject.toml", 99, '"paramiko>=3.4.0, <4.0", # 4.0 removed DSSKey'
                ),
                constraint=">=3.4.0, <4.0",
            ),
            audit.parse_advisory(PARAMIKO_RECORD, {(audit.PYPI, "paramiko"): "3.5.1"}),
            None,
            "4.0.0",
        )
    )

    body = audit.issue_body(candidate, repo=REPO)

    assert PARAMIKO_GHSA in body
    assert PARAMIKO_CVE in body and PARAMIKO_PYSEC in body
    assert "Paramiko rsakey.py allows the SHA-1 algorithm" in body
    assert "`requirements/base.txt:283` — `paramiko==3.5.1`" in body
    assert "`pyproject.toml:99`" in body and "removed DSSKey" in body
    assert "| Installed | `3.5.1` |" in body
    assert "| Severity | Low |" in body
    assert "What a regression test must assert" in body
    assert "tests/unit_tests/**" in body
    # The caveat `docs/remediation-candidates.md` insisted on: OSV never stated the fixed version.
    assert "| Fixed in | _not stated by OSV_ |" in body
    assert "The fixed version is not published." in body
    assert "`last_affected: 4.0.0`" in body
    # Why it survived triage, and how to say it should not have.
    assert "outside `>=3.4.0, <4.0`" in body
    assert "report `outcome: blocked`" in body
    # Reproducible by anyone reading the issue.
    assert "api.osv.dev/v1/querybatch" in body
    assert markers(body) == {f"PyPI/paramiko/{PARAMIKO_GHSA}"}


