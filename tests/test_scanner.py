async def test_a_second_run_over_an_unchanged_tree_files_nothing(
    scanner_settings: Settings, github_api: FakeAPI, osv_api: FakeAPI
) -> None:
    """The property the whole design turns on, exercised as the schedule exercises it.

    The issue list the second run reads is the one the first run wrote into, so nothing about the
    recognition is arranged by the test: if the fingerprint the sweep writes and the fingerprint it
    looks for ever stop being the same string, this fails.
    """
    on_the_repo: list[dict[str, Any]] = []
    serve_tree(github_api)
    serve_osv(osv_api, ALL_RECORDS)
    serve_issues(github_api, on_the_repo)
    serve_creation(github_api)

    async with audit.TargetRepository(scanner_settings) as repository, audit.OsvClient() as osv:
        first = await audit.sweep(tracker=repository, osv=osv, settings=scanner_settings)
        on_the_repo += [
            filed_issue(issue.body, number=issue.number, state="open") for issue in first.filed
        ]
        second = await audit.sweep(tracker=repository, osv=osv, settings=scanner_settings)

    assert len(first.filed) == 2
    assert second.filed == ()
    assert len(github_api.sent("POST", f"/repos/{REPO}/issues")) == 2, "no second attempt"
    assert second.by_reason[audit.Rejected.ALREADY_FILED] == 3, (
        "paramiko, and both image-size advisories, recognised from the two issues filed"
    )


