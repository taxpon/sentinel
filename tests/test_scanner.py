def serve_tree(github: FakeAPI, tree: Mapping[str, str] = TREE) -> None:
    """Answer the contents endpoint for every manifest the sweep asks for, `404` for the rest."""
    for path in (
        audit.PYPROJECT,
        *audit.REQUIREMENTS,
        audit.FRONTEND_PACKAGE_JSON,
        audit.FRONTEND_LOCKFILE,
    ):
        route = github.route("GET", f"/repos/{REPO}/contents/{path}")
        body = tree.get(path)
        route.mock(
            return_value=httpx.Response(200, text=body)
            if body is not None
            else httpx.Response(404, json={"message": "Not Found"})
        )


def serve_osv(osv: FakeAPI, records: Sequence[Mapping[str, Any]]) -> None:
    """A batch endpoint that answers from the query it was sent, and one record per id."""
    by_package: dict[tuple[str, str], list[str]] = {}
    for entry in records:
        for affected in entry["affected"]:
            key = (affected["package"]["ecosystem"], affected["package"]["name"])
            by_package.setdefault(key, []).append(str(entry["id"]))

    def batch(request: httpx.Request) -> httpx.Response:
        queries = json.loads(request.content)["queries"]
        return httpx.Response(
            200,
            json={
                "results": [
                    {
                        "vulns": [
                            {"id": identifier}
                            for identifier in by_package.get(
                                (query["package"]["ecosystem"], query["package"]["name"]), ()
                            )
                        ]
                    }
                    for query in queries
                ]
            },
        )

    osv.route("POST", "/v1/querybatch").mock(side_effect=batch)
    for entry in records:
        osv.responds("GET", f"/v1/vulns/{entry['id']}", 200, entry)


def serve_issues(github: FakeAPI, issues: Sequence[Mapping[str, Any]] = ()) -> None:
    """Answer the issue list from `issues`, re-read on every request.

    Live rather than fixed, so a test can file into the same list the next run reads back — which
    is the loop the whole idempotence claim rests on.
    """
    github.route("GET", f"/repos/{REPO}/issues").mock(
        side_effect=lambda request: httpx.Response(200, json=list(issues))
    )


def serve_creation(github: FakeAPI, start: int = 4200) -> None:
    counter = iter(range(start, start + 50))

    def created(request: httpx.Request) -> httpx.Response:
        sent = json.loads(request.content)
        number = next(counter)
        return httpx.Response(
            201,
            json={
                "number": number,
                "html_url": f"https://github.com/{REPO}/issues/{number}",
                "title": sent["title"],
                "body": sent["body"],
            },
        )

    github.route("POST", f"/repos/{REPO}/issues").mock(side_effect=created)


def filed_issue(body: str, *, number: int = 1, state: str = "open") -> dict[str, Any]:
    return {
        "number": number,
        "html_url": f"https://github.com/{REPO}/issues/{number}",
        "title": "an earlier finding",
        "body": body,
        "state": state,
    }


async def run_sweep(
    settings: Settings,
    github: FakeAPI,
    osv: FakeAPI,
    *,
    tree: Mapping[str, str] = TREE,
    records: Sequence[Mapping[str, Any]] = (),
    issues: Sequence[Mapping[str, Any]] = (),
) -> audit.SweepReport:
    serve_tree(github, tree)
    serve_osv(osv, records)
    serve_issues(github, issues)
    serve_creation(github)
    async with audit.TargetRepository(settings) as repository, audit.OsvClient() as client:
        return await audit.sweep(tracker=repository, osv=client, settings=settings)


def markers(body: str) -> set[str]:
    return set(re.findall(rf"<!-- {audit.MARKER}: (\S+) -->", body))


